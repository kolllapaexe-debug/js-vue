// Паркінг може обробити максимум 7 автомобілів.
//
//     Для кожного автомобіля користувач вводить:
//     1. кількість годин стоянки;
// 2. тип автомобіля:
//     1 — звичайний;
// 2 — електромобіль.
//
//     Правила:
// - якщо замість кількості годин введено 0 — обробку автомобілів потрібно завершити достроково;
// - якщо введено кількість годин менше 0 або більше 12 — такий запис пропустити;
// - звичайний автомобіль: 40 грн за годину;
// - електромобіль: 30 грн за годину;
// - якщо автомобіль стояв більше 5 годин — від підсумкової вартості відняти 20%;
// - якщо тип автомобіля не 1 і не 2 — вивести повідомлення про помилку і перейти до наступного автомобіля.
//
//     Після завершення програма повинна вивести:
//     - кількість правильно оброблених автомобілів;
// - кількість електромобілів;
// - загальну суму оплати;
// - найбільшу оплату за один автомобіль.
//
//     Обов'язково використати:
// - цикл for;
//     - if / else;
//         - break;
// - continue.

let processedCars = 0;
let electricCars = 0;
let total = 0;
let maxPayment = 0;

for (let i = 1; i <= 7; i++) {
    let hours = Number(prompt("Введіть кількість годин стоянки:"));
    if (hours === 0) {
        break;
    }
    if (hours < 0 || hours > 12) {
        alert("Помилка: неправильна кількість годин");
        continue;
    }
    let type = Number(prompt("Введіть тип автомобіля (1 — звичайний, 2 — електромобіль):"));
    if (type !== 1 && type !== 2) {
        alert("Помилка: неправильний тип автомобіля");
        continue;
    }
    let payment;
    if (type === 1) {
        payment = hours * 40;
    } else {
        payment = hours * 30;
        electricCars = electricCars + 1;
    }
    if (hours > 5) {
        payment = payment * 0.8;
    }
    processedCars = processedCars + 1;
    total = total + payment;
    if (payment > maxPayment) {
        maxPayment = payment;
    }
}
alert("Правильно оброблено автомобілів: " + processedCars);
alert("Кількість електромобілів: " + electricCars);
alert("Загальна сума оплати: " + total + " грн");
alert("Найбільша оплата за один автомобіль: " + maxPayment + " грн");


